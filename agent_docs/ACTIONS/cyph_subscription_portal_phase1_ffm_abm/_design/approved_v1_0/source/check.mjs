// Evidence: (1) horizontal overflow for every page × state × theme at 375 and 1440
// (+ mobile menu open where a menu exists); (2) JS errors; (3) the style tile's live
// contrast table in both modes. Writes CHECKS.md. Usage: node check.mjs
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("/opt/npm-tools/node_modules/playwright");
import { writeFileSync, readdirSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
const ROOT = new URL(".", import.meta.url).pathname, DIST = join(ROOT, "dist");
const pages = [
  ...readdirSync(DIST).filter((f) => f.endsWith(".html")).map((f) => ["", f]),
  ...(existsSync(join(DIST, "references")) ? readdirSync(join(DIST, "references")).filter((f) => f.endsWith(".html")).map((f) => ["references", f]) : []),
];
const out = ["# CHECKS — Subscription Portal design package v1.0 (" + new Date().toISOString().slice(0, 10) + ")", "", "Generated by `source/check.mjs` against the built artifacts in `screens/`, `references/` and `style-tile/`.", "",
  "## 1. Horizontal overflow — `max(documentElement.scrollWidth, body.scrollWidth) <= viewport width`", "", "Every page × every declared state × Mist and Slate, at 375 and 1440. Where a page has a mobile menu, 375 is also checked with the menu open. JS errors on load are counted.", ""];
const browser = await chromium.launch();
let fails = 0, total = 0, jsErrors = 0;
for (const [dir, file] of pages) {
  const html = readFileSync(join(DIST, dir, file), "utf8");
  const m = html.match(/data-states="([^"]+)"/); const states = m ? m[1].split(",").map((s) => s.split(":")[0]) : ["default"];
  const hasMenu = html.includes('id="mobile-menu"');
  out.push(`### ${join(dir, file)}`, "", "| State | Mist 375 | Slate 375 | Mist 1440 | Slate 1440 | Menu open (375) |", "|---|---|---|---|---|---|");
  for (const st of states) {
    const cells = [];
    for (const w of [375, 1440]) for (const mode of ["light", "dark"]) {
      const ctx = await browser.newContext({ viewport: { width: w, height: 900 } }); const page = await ctx.newPage();
      page.on("pageerror", () => { jsErrors++; });
      await page.goto(`file://${join(DIST, dir, file)}?mode=${mode}&state=${st}&shot=1`); await page.evaluate(() => document.fonts.ready);
      const sw = await page.evaluate(() => Math.max(document.documentElement.scrollWidth, document.body.scrollWidth));
      total++; const ok = sw <= w; if (!ok) fails++;
      cells.push(ok ? `pass (${sw})` : `**FAIL (${sw})**`);
      await ctx.close();
    }
    let menu = "—";
    if (hasMenu) {
      const res = [];
      for (const mode of ["light", "dark"]) {
        const ctx = await browser.newContext({ viewport: { width: 375, height: 900 } }); const page = await ctx.newPage();
        await page.goto(`file://${join(DIST, dir, file)}?mode=${mode}&state=${st}&shot=1&menu=1`); await page.evaluate(() => document.fonts.ready);
        const sw = await page.evaluate(() => Math.max(document.documentElement.scrollWidth, document.body.scrollWidth));
        total++; const ok = sw <= 375; if (!ok) fails++; res.push(ok ? "pass" : `**FAIL (${sw})**`); await ctx.close();
      }
      menu = res.join(" / ");
    }
    // order: Mist375, Slate375, Mist1440, Slate1440
    out.push(`| ${st} | ${cells[0]} | ${cells[1]} | ${cells[2]} | ${cells[3]} | ${menu} |`);
  }
  out.push("");
}
out.push(`**Result: ${fails === 0 ? "all pass" : fails + " failure(s)"}** across ${total} loads · JS errors on load: ${jsErrors}.`, "");

out.push("## 2. Contrast — live measurement from the style tile (portal tokens)", "", "Small text needs ≥ 4.5:1; large/bold text and non-text edges need ≥ 3:1. Rows marked BEFORE show the inherited fleet values for comparison only.", "");
for (const m of ["light", "dark"]) {
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } }); const page = await ctx.newPage();
  await page.goto(`file://${join(DIST, "style-tile.html")}?mode=${m}&tokens=portal&shot=1`); await page.evaluate(() => document.fonts.ready); await page.waitForTimeout(250);
  const rows = await page.$$eval("#contrast-rows tr", (trs) => trs.map((tr) => Array.from(tr.querySelectorAll("td")).map((td) => td.textContent.trim())));
  out.push(`### ${m === "light" ? "Mist" : "Slate"}`, "", "| Combination | Text/edge | Surface | Ratio | Verdict |", "|---|---|---|---|---|");
  for (const r of rows) out.push("| " + r.join(" | ") + " |");
  out.push(""); await ctx.close();
}
out.push("## 3. Coral button boundary (Mist)", "", "The coral fill measures 2.82:1 against a white Mist card as an *edge*. Resolution recorded in `DECISIONS_AND_DELTAS.md §5`: the button is identified by its 6.06:1 label, and WCAG 1.4.11 does not require a boundary contrast when the control is otherwise identified; in addition every primary button in this package carries a 1px `border-foreground/25` hairline in Mist (`portal-btn` recipe), measured below, so the edge is also visible on white.", "");
{
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } }); const page = await ctx.newPage();
  await page.goto(`file://${join(DIST, "style-tile.html")}?mode=light&tokens=portal&shot=1`); await page.evaluate(() => document.fonts.ready); await page.waitForTimeout(250);
  const r = await page.evaluate(() => {
    const el = document.querySelector('[data-probe="btn-primary"]'); const cs = getComputedStyle(el);
    function parse(c) { const m = c.match(/[\d.]+/g).map(Number); return { r: m[0], g: m[1], b: m[2], a: m.length > 3 ? m[3] : 1 }; }
    function over(f, b) { return { r: f.r * f.a + b.r * (1 - f.a), g: f.g * f.a + b.g * (1 - f.a), b: f.b * f.a + b.b * (1 - f.a), a: 1 }; }
    function lum(c) { const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); }; return 0.2126 * f(c.r) + 0.7152 * f(c.g) + 0.0722 * f(c.b); }
    const card = { r: 255, g: 255, b: 255, a: 1 }; const border = over(parse(cs.borderTopColor), parse(cs.backgroundColor));
    const ratio = (a, b) => { const la = lum(a), lb = lum(b); return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05); };
    return { borderWidth: cs.borderTopWidth, borderVsCard: ratio(border, card).toFixed(2), borderVsFill: ratio(border, parse(cs.backgroundColor)).toFixed(2) };
  });
  out.push(`Primary button hairline: width ${r.borderWidth}; hairline vs white card **${r.borderVsCard}:1**; hairline vs coral fill ${r.borderVsFill}:1.`, "");
  await ctx.close();
}
await browser.close();
writeFileSync(join(ROOT, "CHECKS.md"), out.join("\n"));
